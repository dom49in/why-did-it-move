"""Markovian engine tests.

The numeric contracts are checked against vectors produced by the REAL TypeScript reference
(tests/fixtures/markovian_reference_vectors.json, generated by scripts/gen_markovian_vectors.mjs), so a
regression in the Python port of the efficiency math or the config validation fails here.
"""
import json
import unittest

from app.engines import markovian as mk
from tests.helpers import ROOT

VECTORS = json.loads((ROOT / "tests" / "fixtures" / "markovian_reference_vectors.json").read_text())


def cfg_from(partial: dict) -> dict:
    names = {"chunkSize": "chunk_size", "maxChunks": "max_chunks", "carryoverTokens": "carryover_tokens",
             "overlapTokens": "overlap_tokens"}
    return {names[k]: v for k, v in partial.items()}


class TestAgainstReference(unittest.TestCase):
    def test_run_efficiency_matches_reference(self):
        cfg = mk.resolve_config(**cfg_from(VECTORS["config"]))
        for case in VECTORS["runs"]:
            got = mk.run_efficiency(case["tokens"], cfg)
            ref = case["result"]
            self.assertEqual(got["total_tokens_used"], ref["totalTokensUsed"])
            self.assertEqual(got["standard_cost"], ref["standardCost"])
            self.assertEqual(got["markovian_cost"], ref["markovianCost"])
            self.assertEqual(got["tokens_saved"], ref["tokensSaved"])
            self.assertAlmostEqual(got["efficiency_percent"], ref["efficiencyPercent"], places=9)

    def test_model_totals_matches_reference_and_doc_example(self):
        for case in VECTORS["model"]:
            got, ref = mk.model_totals(case["n"]), case["result"]
            self.assertAlmostEqual(got["naive_total"], ref["naiveTotal"])
            self.assertAlmostEqual(got["markovian_total"], ref["markovianTotal"])
            self.assertAlmostEqual(got["savings"], ref["savings"])
            self.assertAlmostEqual(got["efficiency"], ref["efficiency"], places=12)
        self.assertEqual(round(mk.model_totals(20)["efficiency"] * 100), 86)   # the doc's worked example

    def test_projection_curve_matches_reference(self):
        cfg = mk.resolve_config(**cfg_from(VECTORS["config"]))
        got = mk.projection_curve(cfg, 6)
        self.assertEqual(got, VECTORS["projection"])

    def test_config_validation_matches_reference(self):
        for case in VECTORS["validation"]:
            partial = cfg_from(case["partial"])
            if case["ok"]:
                mk.resolve_config(**partial)
            else:
                with self.assertRaises(mk.ConfigValidationError, msg=case["partial"]):
                    mk.resolve_config(**partial)

    def test_spec_defaults_are_valid_and_overlap_is_rejected_not_ignored(self):
        mk.resolve_config(chunk_size=8000, max_chunks=24, carryover_tokens=800, overlap_tokens=0)   # spec defaults
        with self.assertRaises(mk.ConfigValidationError):
            mk.resolve_config(overlap_tokens=100)   # accepting and ignoring would violate the spec


class TestCarryoverCascade(unittest.TestCase):
    cfg = mk.resolve_config(carryover_tokens=128, chunk_size=3000)

    def test_explicit_accepted_when_in_budget(self):
        text, level = mk.CarryoverService().next("COMPLETED: a\nREMAINING: b\nDECISIONS: c\nCONTEXT: d", [], "", "", self.cfg)
        self.assertEqual(level, "explicit")
        self.assertTrue(text.startswith("COMPLETED:"))

    def test_explicit_rejected_when_too_short_or_too_big(self):
        svc = mk.CarryoverService()
        self.assertNotEqual(svc.next("tiny", [], "", "nothing useful here", self.cfg)[1], "explicit")
        big = "x " * 600
        self.assertNotEqual(svc.next(big, [], "", "", self.cfg)[1], "explicit")

    def test_llm_level_runs_second_and_must_fit(self):
        calls = []

        def compressor(prompt, system):
            calls.append(prompt)
            return "COMPLETED: compressed by the injected model\nREMAINING: x\nDECISIONS: y\nCONTEXT: z"

        text, level = mk.CarryoverService(compressor).next("x " * 600, ["short"], "prev", "chunk body", self.cfg)
        self.assertEqual(level, "llm")
        self.assertIn("Previous state:", calls[0])
        self.assertIn("COMPLETED:", calls[0])

    def test_llm_failure_falls_through_to_heuristic(self):
        def broken(prompt, system):
            raise RuntimeError("api down")

        fallbacks = ["COMPLETED: a smaller rendering that fits\nREMAINING: r\nDECISIONS: d\nCONTEXT: c"]
        text, level = mk.CarryoverService(broken).next("x " * 600, fallbacks, "", "", self.cfg)
        self.assertEqual(level, "heuristic")
        self.assertEqual(text, fallbacks[0])

    def test_key_phrase_heuristic_then_truncation(self):
        svc = mk.CarryoverService()
        text, level = svc.next(None, [], "", "Blah. Decision: use the lift test. Status: two dims probed.", self.cfg)
        self.assertEqual(level, "heuristic")
        self.assertIn("Decision: use the lift test", text)
        long_text = " ".join(f"word{i}" for i in range(2000))
        text, level = svc.next(None, [], "", long_text, self.cfg)
        self.assertEqual(level, "truncation")
        self.assertLessEqual(mk.estimate_tokens(text), self.cfg.carryover_tokens)
        self.assertTrue(text.endswith("word1999"))     # tail-truncated: keeps the most recent words


def synthetic_state(engine, n_findings=8, n_ruled=8):
    state = engine.init_state("Why did the metric move? " * 20, "gross_margin", "2026-08", "2026-09", -50000.0,
                              [{"dimension": d, "rationale": "r" * 90} for d in ("region", "channel", "product")],
                              ["region", "channel", "product", "product_category"], {"product": "product_category"})
    for i in range(n_findings):
        state.findings.append({"id": f"f{i}", "level": 0, "dimension": "region", "member": f"Member number {i}",
                               "scope": [], "delta": -1000.0 - i, "share_of_total": 0.1})
    for i in range(n_ruled):
        state.ruled_out.append({"dimension": f"dim{i}", "scope": "(all)", "why": "diffuse " * 12})
    return state


class TestBoundedState(unittest.TestCase):
    def test_prompt_size_is_flat_while_history_grows(self):
        """30 steps. The prompt must stay inside a fixed bound while a replay-everything prompt keeps growing."""
        engine = mk.MarkovianEngine(mk.resolve_config(max_chunks=32))
        state = synthetic_state(engine)
        history_chars, replay = [], len(engine.SYSTEM)
        for i in range(30):
            obs = {"type": "breakdown", "dimension": "region", "top": [{"member": f"m{j}", "delta": -j * 1.5,
                                                                          "base": 1000.0 + j, "compare": 900.0}
                                                                         for j in range(6)], "query_id": f"q{i}"}
            raw_chars = 4000                                  # what the raw query result would have cost
            msgs = engine.build_step_prompt(state, obs)
            engine.record_step(raw_chars, obs, {"action": "probe", "dimension": "region", "reason": "x"})
            replay += raw_chars
            history_chars.append(replay)
            state.step += 1
        bound = len(engine.SYSTEM) + engine.config.carryover_tokens * 4 + mk.MAX_OBSERVATION_CHARS + 200
        self.assertLessEqual(max(engine.prompt_chars), bound)
        self.assertLess(max(engine.prompt_chars), history_chars[-1] / 20)   # replay would be >20x bigger by step 30
        self.assertGreater(history_chars[-1], 10 * history_chars[0])
        for c in engine.chunks:
            self.assertLessEqual(mk.estimate_tokens(c["carryover"]), engine.config.carryover_tokens)

    def test_oversized_state_degrades_through_the_cascade_but_keeps_the_canonical_shape(self):
        engine = mk.MarkovianEngine(mk.resolve_config(carryover_tokens=128, chunk_size=3000))
        state = synthetic_state(engine)
        text, level = engine.build_carryover(state, "")
        self.assertIn(level, ("heuristic", "truncation"))
        self.assertLessEqual(mk.estimate_tokens(text), 128)
        if level == "heuristic":
            for label in ("COMPLETED:", "REMAINING:", "DECISIONS:", "CONTEXT:"):
                self.assertIn(label, text)

    def test_normal_state_uses_the_canonical_block(self):
        engine = mk.MarkovianEngine()
        state = engine.init_state("why", "revenue", "2026-07", "2026-08", 100.0, [], ["region", "channel"])
        text, level = engine.build_carryover(state)
        self.assertEqual(level, "explicit")
        for label in ("COMPLETED:", "REMAINING:", "DECISIONS:", "CONTEXT:"):
            self.assertIn(label, text)
        self.assertIn("OPEN to probe: region, channel", text)


class TestTransitions(unittest.TestCase):
    def setUp(self):
        self.engine = mk.MarkovianEngine()
        self.state = self.engine.init_state("q", "gross_margin", "2026-08", "2026-09", -100.0, [],
                                            ["region", "product_category", "product"], {"product": "product_category"})

    @staticmethod
    def obs(dim, concentrated, members):
        contribs = [{"member": m, "base": 500.0, "compare": 450.0, "delta": -d, "share": d / 100.0, "lift": 2.0}
                    for m, d in members]
        return {"type": "breakdown", "dimension": dim, "concentrated": concentrated, "query_id": f"q-{dim}",
                "top": contribs, "contributors": contribs if concentrated else [], "why": "diffuse: test"}

    def test_probe_does_not_change_scope_and_diffuse_is_ruled_out(self):
        s = self.engine.transition(self.state, {"action": "probe", "dimension": "region"},
                                   self.obs("region", False, [("A", 30)]))
        self.assertEqual(s.scope, [])
        self.assertEqual(s.ruled_out[0]["dimension"], "region")
        self.assertNotIn("region", s.open_dimensions)
        self.assertEqual(s.descend_options(), [])
        self.assertEqual(self.state.step, 0)             # transition is pure: the input state is untouched

    def test_descend_creates_findings_and_narrows_scope_and_resets_probes(self):
        s = self.engine.transition(self.state, {"action": "probe", "dimension": "region"},
                                   self.obs("region", True, [("A", 60), ("B", 20)]))
        self.assertEqual(s.descend_options(), [("region", 0.6)])
        s = self.engine.transition(s, {"action": "descend", "dimension": "region"},
                                   self.obs("region", True, [("A", 60), ("B", 20)]))
        self.assertEqual([f["member"] for f in s.findings], ["A", "B"])
        self.assertEqual(s.scope, [{"dimension": "region", "member": "A"}])
        self.assertEqual(s.probed, {})
        self.assertNotIn("region", s.open_dimensions)

    def test_child_level_beats_its_parent_and_parent_is_not_reprobed(self):
        s = self.state
        s = self.engine.transition(s, {"action": "probe", "dimension": "product_category"},
                                   self.obs("product_category", True, [("Apparel", 66)]))
        s = self.engine.transition(s, {"action": "probe", "dimension": "product"},
                                   self.obs("product", True, [("Rain Jacket", 58)]))
        self.assertEqual([d for d, _ in s.descend_options()], ["product"])    # 66% parent loses to 58% child
        s = self.engine.transition(s, {"action": "descend", "dimension": "product"},
                                   self.obs("product", True, [("Rain Jacket", 58)]))
        self.assertNotIn("product_category", s.open_dimensions)               # implied by the scope

    def test_depth_limit_stops_the_chain(self):
        s = self.state
        for dim, member in (("region", "A"), ("product", "P")):
            s = self.engine.transition(s, {"action": "probe", "dimension": dim}, self.obs(dim, True, [(member, 60)]))
            s = self.engine.transition(s, {"action": "descend", "dimension": dim}, self.obs(dim, True, [(member, 60)]))
        self.assertEqual(s.stopped, "max_depth")
        self.assertEqual(self.engine.should_stop(s), (True, "max_depth"))
        self.assertEqual(self.engine.status_for("max_depth"), "completed")
        self.assertEqual(self.engine.status_for("step_budget"), "max-chunks")

    def test_stop_conditions(self):
        self.assertEqual(self.engine.should_stop(self.state), (False, ""))
        done = self.engine.init_state("q", "revenue", "2026-07", "2026-08", 1.0, [], [])
        self.assertEqual(self.engine.should_stop(done), (True, "exhausted"))


class TestRecordsAndHistory(unittest.TestCase):
    def test_run_record_has_the_mandatory_config_snapshot_and_spec_fields(self):
        engine = mk.MarkovianEngine(mk.resolve_config(carryover_tokens=300))
        state = synthetic_state(engine, 1, 1)
        engine.build_step_prompt(state, {"type": "total"})
        engine.record_step(800, {"type": "breakdown"}, {"action": "probe", "dimension": "region"})
        run = engine.run_record("why?", "completed", 12)
        for key in ("id", "timestamp", "prompt", "mode", "chunkConfig", "chunks", "totalTokensUsed", "totalTokensSaved",
                    "efficiencyPercent", "durationMs", "status", "tokenLabel"):
            self.assertIn(key, run)
        self.assertEqual(run["chunkConfig"]["carryover_tokens"], 300)       # the run's OWN config, not the default
        self.assertEqual(run["tokenLabel"], "estimated")
        self.assertEqual(set(run["chunks"][0]), {"id", "tokens", "carryover", "content"})

    def test_measured_tokens_are_only_reported_when_every_step_has_usage(self):
        engine = mk.MarkovianEngine()
        engine.note_usage({"prompt_tokens": 100})
        engine.note_usage(None)
        self.assertIsNone(engine.stats()["measured_prompt_tokens_per_step"])
        engine2 = mk.MarkovianEngine()
        engine2.note_usage({"prompt_tokens": 100})
        self.assertEqual(engine2.stats()["measured_prompt_tokens_per_step"], [100])

    def test_history_and_cumulative_stats(self):
        import tempfile, pathlib
        with tempfile.TemporaryDirectory() as d:
            hist = mk.RunHistory(pathlib.Path(d) / "h.jsonl")
            self.assertEqual(hist.cumulative()["totalRuns"], 0)
            hist.record({"timestamp": 1, "status": "completed", "totalTokensUsed": 100, "totalTokensSaved": 20,
                         "efficiencyPercent": 10.0, "chunks": [1, 2]})
            hist.record({"timestamp": 2, "status": "max-chunks", "totalTokensUsed": 50, "totalTokensSaved": 0,
                         "efficiencyPercent": 0.0, "chunks": [1]})
            c = hist.cumulative()
            self.assertEqual((c["totalRuns"], c["completedRuns"], c["totalTokensUsed"], c["totalTokensSaved"],
                              c["totalChunksProcessed"], c["lastRunTimestamp"]), (2, 1, 150, 20, 3, 2))
            self.assertAlmostEqual(c["averageEfficiency"], 5.0)
            self.assertEqual(len(c["efficiencyHistory"]), 2)


