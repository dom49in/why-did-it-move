-- ===== PART B: fx_rates_table (web API) =====
-- Register the second data source in Zetaris: a PUBLIC WEB API (Frankfurter exchange rates, no API key).
-- The agent never calls the web itself. It queries the Zetaris view created below, through the same Zetaris
-- REST SQL endpoint it uses for the sales table. Set  ZETARIS_FX_TABLE=sales.fx_rates_table  in .env afterwards.
--
-- STATUS: run in the author's own Zetaris Docker instance; the live example runs read this view. Run the blocks one
-- at a time and stop at the first failure. If step 3 fails or the view shows no rows, use VARIANT B (response wrapped
-- in a "data" array) and check Zetaris's Troubleshooting page.
--
-- Data: https://frankfurter.dev (rates from central banks, e.g. the ECB). Change `from`/`to` to cover your periods.
-- Any REST API that returns one row per observation with a date and a numeric value works the same way;
-- only the view's four column names matter: rate_date, base_currency, quote_currency, rate.

-- 1. Logical database
CREATE LIGHTNING DATABASE sales_demo DESCRIBE BY "Sales demo: sales facts and exchange rates";  -- skip if it already exists

-- 2. Raw REST table. It re-fetches the API on EVERY query unless cached (step 3), so cache it.
CREATE LIGHTNING REST TABLE fx_raw FROM sales_demo REQUEST(
    endpoint "https://api.frankfurter.dev/v2/rates?from=2026-04-01&to=2026-10-31&base=USD&quotes=CAD",
    method "get",
    response_type "json",
    http_encoding "URLENCODED"
) HEADER (
) BODY ();

-- 3. Cache it
CACHE TABLE sales_demo.fx_raw;

-- 4. Container and view (VARIANT A: the API returns a top-level array of {date, base, quote, rate})

CREATE SCHEMASTORE VIEW fx_rates_table WITH CONTAINER sales AS
SELECT `date` AS rate_date, base AS base_currency, quote AS quote_currency, CAST(rate AS DOUBLE) AS rate
FROM sales_demo.fx_raw;

